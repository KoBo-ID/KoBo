import { test, expect } from '@playwright/test'
import { loginAs } from '../tests/fixtures'
async function localOnly(context: import('@playwright/test').BrowserContext) {
  await context.route('**/*', route => ['localhost','127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
}
test('E1 demo survey apply approve and pay', async ({ page, browser }) => {
  await localOnly(page.context())
  await loginAs(page, 'student')
  await page.goto('/kos/kos-1')
  await page.getByRole('button', { name: 'Jadwalkan Survey Gratis' }).first().click()
  await page.getByLabel('Nomor WhatsApp').fill('081234567890')
  await page.getByRole('button', { name: 'Konfirmasi Jadwal Survey Gratis' }).click()
  await expect(page.getByText('berhasil dikonfirmasi')).toBeVisible()
  await page.goto('/my-kos')
  await page.getByRole('tab', { name: /Jadwal Survey Gratis/ }).click()
  await expect(page.getByText('Terjadwal').first()).toBeVisible()
  await page.goto('/kos/kos-1')
  await page.getByRole('button', { name: 'Ajukan Sewa' }).click()
  await expect(page).toHaveURL(/\/checkout\/kos-1\?room=/)
  await page.getByLabel('Pekerjaan atau kegiatan utama').fill('Audit mahasiswa')
  await page.getByRole('button', { name: 'Kirim Pengajuan' }).click()
  await expect(page.getByRole('heading', { name: 'Pengajuan Terkirim' })).toBeVisible()
  await page.getByRole('link', { name: 'Pantau Pengajuan' }).click()
  await page.getByRole('tab', { name: /Pengajuan Sewa/ }).click()
  await expect(page.getByTestId('application-card').filter({hasText:'Wisma Sakura'})).toContainText('Menunggu Pemilik')
  const owner = await browser.newContext({baseURL:'http://localhost:3100',reducedMotion:'reduce'})
  await localOnly(owner)
  const op = await owner.newPage()
  await loginAs(op, 'owner')
  await op.goto('/owner/dashboard?kos=kos-1&tab=tindakan')
  await op.getByTestId('owner-application').filter({hasText:'Audit mahasiswa'}).getByRole('button',{name:'Terima'}).click()
  await op.getByRole('dialog').getByRole('button',{name:'Terima Pengajuan'}).click()
  await expect(op.getByTestId('owner-application').filter({hasText:'Audit mahasiswa'})).toHaveCount(0)
  await page.reload()
  await page.getByRole('tab',{name:/Pengajuan Sewa/}).click()
  await expect(page.getByTestId('application-card').filter({hasText:'Wisma Sakura'})).toContainText('Diterima')
  await page.getByRole('tab',{name:/Kamar yang Disewa/}).click()
  await page.getByRole('button',{name:'Bayar Sekarang'}).click()
  await page.getByRole('button',{name:'Selesaikan Pembayaran'}).click()
  await expect(page).toHaveURL(/\/my-kos/)
  const card = page.getByTestId('tenancy-card').filter({hasText:'Wisma Sakura'}).first()
  await expect(card).toHaveAttribute('data-status','ACTIVE')
  await page.reload()
  await page.getByRole('tab',{name:/Kamar yang Disewa/}).click()
  await expect(page.getByTestId('tenancy-card').filter({hasText:'Wisma Sakura'}).first()).toHaveAttribute('data-status','ACTIVE')
  await owner.close()
})
