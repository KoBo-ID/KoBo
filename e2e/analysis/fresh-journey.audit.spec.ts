import {test,expect} from './safe-fixtures'
import {outboxLink,ownIp} from '../tests/accounts'
import {newOwnerWorld,sql,stubXenditCheckout,latestPayment,webhook,sessionCompleted} from '../tests/seams'

test('E2 fresh registration to mocked settlement and receipts',async({page,browser})=>{
  const owner=await newOwnerWorld(browser,{label:'audit-fresh-owner',rooms:1})
  try {
    await ownIp(page)
    const email=`audit-fresh-${Date.now()}@example.com`
    await page.goto('/masuk')
    await page.getByRole('button',{name:'Daftar baru'}).click()
    await page.getByLabel('Nama Lengkap').fill('Penguji Audit')
    await page.getByLabel('Email').fill(email)
    await page.getByLabel('Kata Sandi').fill('Sandi-rahasia-123')
    await page.getByLabel(/Saya menyetujui/).check()
    await page.getByRole('button',{name:'Daftar Sekarang'}).click()
    await expect(page.getByText('Cek email Anda').first()).toBeVisible()
    await page.goto(await outboxLink(email,'verify-email'))
    await expect(page.getByRole('heading',{name:'Email berhasil diverifikasi'})).toBeVisible()
    await page.goto('/profile')
    const campus=`audit${Date.now()}@student.binus.ac.id`
    await page.getByLabel('Email Kampus').fill(campus)
    await page.getByRole('button',{name:'Kirim Tautan Verifikasi'}).click()
    await expect(page.getByText(`Tautan verifikasi terkirim ke ${campus}`)).toBeVisible()
    await page.goto(await outboxLink(campus,'campus-email'))
    await expect(page.getByText('Email kampus terverifikasi').first()).toBeVisible()
    const contact=page.getByTestId('emergency-contact-card')
    await contact.getByRole('button',{name:'Isi kontak darurat'}).click()
    await contact.getByLabel('Nama',{exact:true}).fill('Kontak Uji')
    await contact.getByLabel('Hubungan').fill('Keluarga')
    await contact.getByLabel('Nomor WhatsApp').fill('0812 3456 7890')
    await contact.getByLabel(/Saya sudah memberi tahu orang ini/).check()
    await contact.getByRole('button',{name:'Simpan'}).click()
    await page.reload(); await expect(contact).toContainText('Kontak Uji')
    await page.goto(`/kos/${owner.kosId}`)
    await page.getByRole('button',{name:'Ajukan Sewa'}).click()
    await page.getByLabel('Pekerjaan atau kegiatan utama').fill('Mahasiswa audit fresh')
    await page.getByRole('button',{name:'Kirim Pengajuan'}).click()
    await expect(page.getByRole('heading',{name:'Pengajuan Terkirim'})).toBeVisible()
    await owner.page.goto(`/owner/dashboard?kos=${owner.kosId}&tab=tindakan`)
    const app=owner.page.getByTestId('owner-application').filter({hasText:'Mahasiswa audit fresh'})
    await app.getByRole('button',{name:'Terima'}).click()
    await owner.page.getByRole('dialog').getByRole('button',{name:'Terima Pengajuan'}).click()
    await expect(app).toHaveCount(0)
    const [invoice]=await sql<{id:string}>(`SELECT i.id FROM "Invoice" i JOIN "Tenancy" t ON t.id=i."tenancyId" JOIN "User" u ON u.id=t."userId" WHERE u.email=$1 AND t."roomId"=$2`,[email,owner.rooms[0].id])
    expect(invoice).toBeTruthy()
    await stubXenditCheckout(page.context())
    await page.goto('/my-kos')
    const card=page.getByTestId('tenancy-card').filter({hasText:owner.kosName})
    const bill=card.getByRole('row').filter({hasText:'Bulan 1'})
    await bill.getByRole('button',{name:'Bayar Sekarang'}).click()
    await page.waitForURL(/^https:\/\/checkout-staging\.xendit\.co\//)
    const payment=await latestPayment(invoice.id)
    expect((await webhook(page.request,sessionCompleted(payment.id,payment.amount))).json.result).toBe('SETTLED')
    await page.getByRole('link',{name:'Bayar (simulasi)'}).click()
    await expect(page).toHaveURL(/\/my-kos/)
    await expect(card).toHaveAttribute('data-status','ACTIVE')
    await card.getByRole('link',{name:/Kuitansi/}).first().click()
    await expect(page.getByTestId('kuitansi-no')).toHaveText(/^KB\/\d{4}\/\d{2}\/\d{4}$/)
    await page.reload(); await expect(page.getByTestId('kuitansi-no')).toBeVisible()
    await owner.page.goto(`/owner/dashboard?kos=${owner.kosId}`)
    const row=owner.page.getByRole('row').filter({hasText:`Kamar ${owner.rooms[0].roomNumber}`})
    await expect(row.getByText('Lunas',{exact:true})).toBeVisible()
    await row.getByRole('link',{name:/Lihat kuitansi Kamar/}).click()
    await expect(owner.page.getByTestId('kuitansi-no')).toHaveText(/^KB\/\d{4}\/\d{2}\/\d{4}$/)
  } finally { await owner.ctx.close() }
})
