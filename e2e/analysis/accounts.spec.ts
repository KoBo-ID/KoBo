import { test, expect } from '@playwright/test'
import { outboxLink, ownIp, signUpVerified } from '../tests/accounts'
test.use({ trace:'off', screenshot:'off' })
test.beforeEach(async ({page}) => {
  await page.route('**/*', route => ['localhost','127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  await ownIp(page)
})
test('B1 register and verify through outbox', async ({page}) => {
  await page.goto('/masuk')
  await page.getByRole('button',{name:'Daftar baru'}).click()
  const email = `audit-${Date.now()}@example.com`
  await page.getByLabel('Nama Lengkap').fill('Penguji Audit')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Kata Sandi').fill('Sandi-rahasia-123')
  await page.getByLabel(/Saya menyetujui/).check()
  await page.getByRole('button',{name:'Daftar Sekarang'}).click()
  await expect(page.getByText('Cek email Anda').first()).toBeVisible()
  await page.goto(await outboxLink(email,'verify-email'))
  await expect(page.getByRole('heading',{name:'Email berhasil diverifikasi'})).toBeVisible()
})
test('B3 password reset and old password invalidation', async ({page}) => {
  const email = await signUpVerified(page,'audit-reset')
  await page.context().clearCookies()
  await page.goto('/masuk')
  await page.getByRole('button',{name:'Lupa kata sandi?'}).click()
  await page.getByLabel('Email').fill(email)
  await page.getByRole('button',{name:'Kirim Tautan Atur Ulang'}).click()
  await expect(page.getByText(/telah mengirim tautan untuk mengatur ulang/)).toBeVisible()
  await page.goto(await outboxLink(email,'reset-password'))
  await page.getByLabel('Kata Sandi Baru',{exact:true}).fill('Sandi-baru-456')
  await page.getByLabel('Ulangi Kata Sandi Baru').fill('Sandi-baru-456')
  await page.getByRole('button',{name:'Simpan Kata Sandi Baru'}).click()
  await expect(page.getByRole('heading',{name:'Kata sandi diperbarui'})).toBeVisible()
  await page.goto('/masuk')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Kata Sandi').fill('Sandi-rahasia-123')
  await page.getByRole('button',{name:'Masuk ke Akun'}).click()
  await expect(page.getByRole('alert')).toContainText('Email atau kata sandi salah')
})
